/* ── 0) 整地 ──────────────────────────────────────────────────────────────────
   一定要在 parcels() 之前（也就是 prepare 裡）做完：parcels 用可達性決定哪些格能蓋。
   ※ (13,14) 原本是一格卡住水井口袋的 e1 樹林，過去要手動清成空地才走得通；
     水塘全部壓平為平地之後，這一帶四周都是 e1 平地，`layRoads()` 的自動鋪路
     在 prepare() 執行前就已經把它鋪成 wood_path，不再需要這裡手動整地。 */
function prepareTerrain(g) {
    /* 原生鱷魚池 (7,23)：四鄰是東北角湖與竹林，附近僅有的兩格空地 (5,23)/(6,22) 互為斜角、
       彼此不相鄰，兩格自己也被湖包住 → 開局就是「被包圍的建築」。maxCarve = 0 之下
       唯一解是拆遷，改在北高地的「高原動物園」重建（鱷魚／熊貓／無尾熊都不是任何景點的
       材料，搬家對景點零風險）。**這是全圖唯一一棟拆遷。** */
    g[7][23] = { type: 'woods', elevation: 1 };
    console.log('  拆遷原生鱷魚池 @X9/Y2（被東北角湖圈死）→ 北高地動物園重建');

    /* 原生開羅君像 (0,20)＝X2/Y5：**配額只有 1 座**，而「開羅」景點要在南邊
       （金開羅君＋開羅君像＋開羅君房間擠同一個 4×4）湊出一座，兩座並存蓋不出來。
       這一座又蓋在北高地、開局走不到，而且要第 8 年才解鎖——留著純虧 500 G/月。
       所以開局就拆掉，第 4 階再蓋到南邊走得到的位置（與攻略第 1 階的指示一致）。 */
    g[0][20] = { type: 'empty', elevation: g[0][20].elevation };
    console.log('  拆除原生開羅君像 @X2/Y5（配額只有 1 座，要留給南邊的「開羅」景點）');

    /* 原生養雞小屋 (21,8)＝X23/Y17：不是 29 個景點裡任何一個的材料，100 G/月 純支出。
       北岸動物園那一區本來就會擺養雞，這一座是多的。 */
    g[21][8] = { type: 'empty', elevation: g[21][8].elevation };
    console.log('  拆除原生養雞小屋 @X23/Y17（不是任何景點的材料）');
}

