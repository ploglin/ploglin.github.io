/* ── 0) 整地 ──────────────────────────────────────────────────────────────────
   一定要在 parcels() 之前（也就是 prepare 裡）做完：parcels 用可達性決定哪些格能蓋，
   (13,14) 沒清的話整個水井口袋都算走不到。 */
function prepareTerrain(g) {
    /* ★ 踏石橋：(13,14) 是一格 **e2 樹林**，夾在 (13,13)／(12,14)／(14,14) 三格 e1 之間。
       清成空地後 `isSlope` 由高低差自動推導成立 → e1↔e2↔e1 變成一座免費的斜坡橋，
       一次做到三件事：①打通「水井口袋」（(12,14)–(12,17)/(13,15)–(13,17) 七格＋原生水井
       (13,18)，開局是走不到的）②多開一條南北通道 ③「水岸」「力量」兩個景點的窗口。
       **這是「不鑿一格湖」還能維持動線的關鍵**，也是本管線把「斜坡是算出來的」當
       攻擊手段而不是限制的代表作。 */
    if (g[13][14].type !== 'woods' || g[13][14].elevation !== 2) throw new Error('(13,14) 不是 e2 樹墩');
    g[13][14] = { type: 'empty', elevation: 2 };
    console.log('  清 (13,14) 樹墩 → e2 斜坡踏石橋：打通水井口袋＋第二條南北通道（X15/Y11）');

    /* 原生鱷魚池 (7,23)：四鄰是東北角湖與竹林，附近僅有的兩格空地 (5,23)/(6,22) 互為斜角、
       彼此不相鄰，兩格自己也被湖包住 → 開局就是「被包圍的建築」。maxCarve = 0 之下
       唯一解是拆遷，改在北高地的「高原動物園」重建（鱷魚／熊貓／無尾熊都不是任何景點的
       材料，搬家對景點零風險）。**這是全圖唯一一棟拆遷。** */
    g[7][23] = { type: 'woods', elevation: 1 };
    console.log('  拆遷原生鱷魚池 @X9/Y2（被東北角湖圈死）→ 北高地動物園重建');
}

